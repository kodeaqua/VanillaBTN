"""Generate the native Q12 sine reference from the mathematical definition.

This uses no disc/SDK table. Native builds consume the checked-in integers and
do not require Python or floating-point trig at runtime.
"""

import math
from pathlib import Path


def table() -> str:
    values = [int(math.sin(index * math.pi / 2048) * 4096 + 0.5) for index in range(1025)]
    lines = ["/* Generated by port/analysis/generate_trig.py from analytic sine, not SDK data. */",
             "static const s16 hm_sine_quadrant[1025] = {"]
    for start in range(0, len(values), 16):
        lines.append("    " + ", ".join(str(value) for value in values[start:start + 16]) + ",")
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "psx/trig_table.inc"
    destination.write_text(table(), encoding="utf-8")
